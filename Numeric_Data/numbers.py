# Integers (whole numbers)
num1 = 10
num2 = 3
print("num1:", num1)
print("num2:", num2)

# Floats (decimal numbers)
num3 = 10.5
num4 = 3.2
print("num3:", num3)
print("num4:", num4)

# Basic Arithmetic
print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2) 
print("Floor Division:", num1 // num2) 
print("Modulus (Remainder):", num1 % num2)
print("Exponent (Power):", num1 ** num2) 

# Mixing Integers and Floats
result = num1 + num3
print("Result:", result, "Type:", type(result))

#  Built-in Functions
num = -7.9
print("abs(num):", abs(num))      
print("round(num):", round(num)) 
print("round(num, 1):", round(num, 1))  

# Order of Operations
print("2 + 3 * 4 =", 2 + 3 * 4)       
print("(2 + 3) * 4 =", (2 + 3) * 4) 

# Comparisons
print("(num1 == num2):", num1 == num2)
print("(num1 != num2):", num1 != num2)
print("(num1 > num2):", num1 > num2)
print("(num2 < num1):", num2 < num1)
print("(num1 >= 10):", num1 >= 10)
print("(num2 <= 3):", num2 <= 3)

num_1 = '100'
num_2 = '200'
print(num_1 + num_2)

num_1 = int(num_1)
num_2 = int(num_2)
print(num_1 + num_2)

